func jsUppercase(text string) string {
	var upper strings.Builder
	for _, r := range text {
		if expansion, ok := jsUppercaseExpansions[r]; ok {
			upper.WriteString(expansion)
		} else {
			upper.WriteRune(unicode.ToUpper(r))
		}
	}
	return upper.String()
}
